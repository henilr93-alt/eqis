  const successRate = input.overallSuccessRate != null ? input.overallSuccessRate : (totals.totalSearches ? (totals.totalSuccess / totals.totalSearches) * 100 : 0);
  const spfRate     = input.spfRate != null ? input.spfRate : (totals.totalSearches ? ((totals.totalEtravIssues || 0) / totals.totalSearches) * 100 : 0);

  // ── Hero status ──────────────────────────────────────────────────
  const heroColor = (totals.totalEtravIssues || 0) > 5 ? '#a40000' : (totals.totalEtravIssues || 0) > 0 ? '#7a5400' : '#0a7f3f';
