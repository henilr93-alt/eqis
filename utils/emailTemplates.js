/* ────────────────────────────────────────────────────────────────────── *
 *  MARKETING TEAM — ECD "Promote" digest (good pricing = ECD cheaper)
 * ────────────────────────────────────────────────────────────────────── */

function ecdHotelRowAction(row) {
  let ecdN = 0, normN = 0;
  for (const c of (row.combos || [])) {
    if (c.verdict === 'ECD_CHEAPER') ecdN++;
    else if (c.verdict === 'NORMAL_CHEAPER') normN++;
  }
  const c0 = (row.combos || [])[0] || null;
  const isPromote = ecdN > 0 && normN === 0;
  const isReneg   = normN >= ecdN && normN > 0;
  const c0v = c0 && c0.verdict;
  const c0Diff = c0 && c0.diff && typeof c0.diff.absINR === 'number' ? c0.diff.absINR : null;
  const c0Pct  = c0 && c0.diff && typeof c0.diff.pct === 'number'    ? c0.diff.pct    : null;
  const ecdT  = c0 && c0.ecd    && typeof c0.ecd.totalPrice    === 'number' ? c0.ecd.totalPrice    : null;
  const normT = c0 && c0.normal && typeof c0.normal.totalPrice === 'number' ? c0.normal.totalPrice : null;
  const N = nights(row.checkin, row.checkout);
  const R = Math.max(1, Number((row.pax && row.pax.rooms) || row.rooms || 1));
  const unit = Math.max(1, N * R);
  const savingINR = (c0v === 'ECD_CHEAPER' && c0Diff != null) ? Math.abs(c0Diff) : 0;
  const overpayINR = (c0v === 'NORMAL_CHEAPER' && c0Diff != null) ? Math.abs(c0Diff) : 0;
  return {
    isPromote, isReneg,
    ecdTotal: ecdT, normTotal: normT,
    ecdPerNight: ecdT != null ? Math.round(ecdT / unit) : null,
    normPerNight: normT != null ? Math.round(normT / unit) : null,
    savingTotal: savingINR, savingPerNight: Math.round(savingINR / unit),
    overpayTotal: overpayINR, overpayPerNight: Math.round(overpayINR / unit),
    pct: c0Pct != null ? Math.abs(c0Pct) : 0,
    nights: N, rooms: R,
    roomName: c0 ? c0.roomCategory : '',
    mealName: c0 ? c0.mealPlan : '',
  };
}

// 2026-06-12: per user request — both promote and renegotiate digests now
// cap at 3 hotels and show a room-by-room price-difference table inside
// each hotel card. This shared helper renders one hotel "card" with all of
// its matching combos. `mode` controls colour scheme + header label.
//
//   mode='promote'   → green; column header "You save"
//   mode='renegotiate' → red;   column header "You overpay"
function _ecdHotelCardHtml(hotel, matchingCombos, mode, index) {
  const colorAccent = mode === 'promote' ? '#0a7f3f' : '#a40000';
  const bgAccent    = mode === 'promote' ? '#e6f7ec' : '#fef2f2';
  const diffLabel   = mode === 'promote' ? 'You save'  : 'You overpay';
  const diffSign    = mode === 'promote' ? '-' : '+';

  const N = nights(hotel.checkin, hotel.checkout);
  const R = Math.max(1, Number((hotel.pax && hotel.pax.rooms) || hotel.rooms || 1));
  const unit = Math.max(1, N * R);

  let hotelTotalDiff = 0;
  const comboRows = matchingCombos.map((c) => {
    const ecdT  = c.ecd    && typeof c.ecd.totalPrice    === 'number' ? c.ecd.totalPrice    : null;
    const normT = c.normal && typeof c.normal.totalPrice === 'number' ? c.normal.totalPrice : null;
    const absINR = c.diff && typeof c.diff.absINR === 'number' ? Math.abs(c.diff.absINR) : 0;
    const pct    = c.diff && typeof c.diff.pct    === 'number' ? Math.abs(c.diff.pct)    : 0;
    hotelTotalDiff += absINR;
    const ecdPerNight  = ecdT  != null ? Math.round(ecdT  / unit) : null;
    const normPerNight = normT != null ? Math.round(normT / unit) : null;
    const diffPerNight = Math.round(absINR / unit);
    return '<tr>'
      + '<td style="padding:8px 12px;font-size:12px;border-bottom:1px solid #f0f0f0;vertical-align:top;">'
      +   '<div style="font-weight:600;">' + esc(c.roomCategory || 'Room category') + '</div>'
      +   (c.mealPlan ? '<div style="font-size:10px;color:#888;margin-top:1px;">' + esc(c.mealPlan) + '</div>' : '')
      + '</td>'
      + '<td style="padding:8px 12px;text-align:right;font-size:12px;border-bottom:1px solid #f0f0f0;vertical-align:top;font-variant-numeric:tabular-nums;">'
      +   '<div style="font-weight:600;">' + fmtINR(ecdPerNight) + '</div>'
      +   '<div style="font-size:10px;color:#888;">' + fmtINR(ecdT) + ' total</div>'
      + '</td>'
      + '<td style="padding:8px 12px;text-align:right;font-size:12px;border-bottom:1px solid #f0f0f0;vertical-align:top;font-variant-numeric:tabular-nums;color:#555;">'
      +   '<div>' + fmtINR(normPerNight) + '</div>'
      +   '<div style="font-size:10px;color:#888;">' + fmtINR(normT) + ' total</div>'
      + '</td>'
      + '<td style="padding:8px 12px;text-align:right;font-size:12px;border-bottom:1px solid #f0f0f0;vertical-align:top;font-variant-numeric:tabular-nums;color:' + colorAccent + ';">'
      +   '<div style="font-weight:700;">' + fmtINR(diffPerNight) + '</div>'
      +   '<div style="font-size:10px;">' + diffSign + pct.toFixed(1) + '% · ' + fmtINR(absINR) + ' total</div>'
      + '</td>'
      + '</tr>';
  }).join('');

  return '<div style="border:1px solid #eee;border-radius:8px;overflow:hidden;margin-bottom:14px;">'
    +   '<div style="padding:12px 16px;background:' + bgAccent + ';border-bottom:1px solid #eee;">'
    +     '<div style="display:inline-block;font-weight:700;font-size:11px;color:' + colorAccent + ';background:#fff;border:1px solid ' + colorAccent + '20;padding:1px 6px;border-radius:4px;margin-right:6px;">' + index + '</div>'
    +     '<span style="font-weight:700;font-size:14px;color:#0a0a0a;">' + esc(hotel.hotelName) + '</span>'
    +     '<div style="font-size:11px;color:#666;margin-top:3px;">' + esc(hotel.destination || '') + (hotel.city ? ' · ' + esc(hotel.city) : '') + (hotel.starRating ? ' · ' + hotel.starRating + '★' : '') + ' · ' + N + ' night' + (N > 1 ? 's' : '') + (R > 1 ? ' × ' + R + ' rooms' : '') + ' · ' + matchingCombos.length + ' room category' + (matchingCombos.length === 1 ? '' : 'ies') + ' to ' + (mode === 'promote' ? 'promote' : 'renegotiate') + '</div>'
    +   '</div>'
    +   '<table width="100%" cellpadding="0" cellspacing="0" style="border-collapse:collapse;">'
    +     '<thead><tr style="background:#fafafa;">'
    +       '<th style="padding:8px 12px;text-align:left;font-size:10px;color:#666;font-weight:600;text-transform:uppercase;letter-spacing:.05em;border-bottom:1px solid #eee;">Room + meal plan</th>'
    +       '<th style="padding:8px 12px;text-align:right;font-size:10px;color:#666;font-weight:600;text-transform:uppercase;letter-spacing:.05em;border-bottom:1px solid #eee;">Your rate /night</th>'
    +       '<th style="padding:8px 12px;text-align:right;font-size:10px;color:#666;font-weight:600;text-transform:uppercase;letter-spacing:.05em;border-bottom:1px solid #eee;">Market /night</th>'
    +       '<th style="padding:8px 12px;text-align:right;font-size:10px;color:#666;font-weight:600;text-transform:uppercase;letter-spacing:.05em;border-bottom:1px solid #eee;">' + diffLabel + ' /night</th>'
    +     '</tr></thead>'
    +     '<tbody>' + comboRows + '</tbody>'
    +   '</table>'
    + '</div>';
}

// 2026-06-12: hotels are now ranked + capped at 3 (per user). Each hotel
// expands to show every matching combo (room category + meal plan + rates).
const HOTEL_CARD_LIMIT = 3;

function renderMarketingDigest(input) {
  const hotels = Array.isArray(input.hotels) ? input.hotels : [];
  // 2026-06-12: per user — exactly ONE destination per day, exactly 3 hotels
  // from that destination. Rotation = least-recently-used destination wins;
  // within the chosen destination, prefer hotels not shown in the last 7 days.
  const rotation = require('./marketingRotation');
  const candidates = hotels.map(h => {
    const combos = (h.combos || []).filter(c => c.verdict === 'ECD_CHEAPER' && c.diff && typeof c.diff.absINR === 'number');
    if (combos.length === 0) return null;
    const totalSaving = combos.reduce((acc, c) => acc + Math.abs(c.diff.absINR), 0);
    return { hotelName: h.hotelName, destination: h.destination || 'Unknown', row: h, combos, totalSaving };
  }).filter(Boolean);
  const byDest = {};
  for (const c of candidates) {
    if (!byDest[c.destination]) byDest[c.destination] = [];
    byDest[c.destination].push(c);
  }
  for (const dest of Object.keys(byDest)) {
    byDest[dest].sort((a, b) => b.totalSaving - a.totalSaving);
  }
  const availableDestinations = Object.keys(byDest).filter(d => byDest[d].length > 0);
  const chosenDestination = rotation.pickDestinationForToday(availableDestinations);
  const HOTEL_LIMIT = 3;
  let picked = [];
  let destinationGroups = [];
  let totalSavings = 0;
  if (chosenDestination) {
    picked = rotation.pickFreshHotels(chosenDestination, byDest[chosenDestination], HOTEL_LIMIT);
    if (picked.length > 0) {
      destinationGroups = [{ destination: chosenDestination, items: picked }];
      rotation.recordSent(chosenDestination, picked.map(p => p.hotelName));
      rotation.recordDestinationSent(chosenDestination);
      picked.forEach(p => { totalSavings += p.totalSaving; });
    }
  }
  // 4. Render: a destination header + 3 hotel cards beneath each
  const destinationBlocks = destinationGroups.map(g => {
    const header = '<div style="margin:24px 0 10px;font-size:15px;font-weight:700;color:#0a0a0a;text-transform:uppercase;letter-spacing:.04em;border-bottom:2px solid #0a7f3f;padding-bottom:6px;">'
      + '\u{1F4CD} ' + esc(g.destination)
      + ' <span style="font-size:11px;font-weight:600;color:#0a7f3f;letter-spacing:0;text-transform:none;">'
      + g.items.length + ' hotel' + (g.items.length === 1 ? '' : 's') + ' to promote</span>'
      + '</div>';
    const cards = g.items.map((it, i) => _ecdHotelCardHtml(it.row, it.combos, 'promote', i + 1)).join('');
    return header + cards;
  }).join('');
  const totalHotels = picked.length;

  const body = [
    '<div style="background:#e6f7ec;border:1px solid #cce7d8;border-radius:6px;padding:16px;margin-bottom:18px;">',
    '<div style="font-size:11px;font-weight:700;color:#0a7f3f;letter-spacing:.05em;text-transform:uppercase;">Today\'s top wins</div>',
    '<div style="font-size:28px;font-weight:700;color:#0a7f3f;font-variant-numeric:tabular-nums;margin-top:4px;">' + totalHotels + ' hotel' + (totalHotels === 1 ? '' : 's') + '</div>',
    '<div style="font-size:13px;color:#0a5f2e;margin-top:2px;">' + (chosenDestination ? 'featured destination: ' + esc(chosenDestination) + ' \u2014 ' : '') + 'total potential ' + fmtINR(totalSavings) + ' in savings to highlight</div>',
    '</div>',
    totalHotels === 0
      ? '<div style="padding:16px;text-align:center;color:#7a5400;font-weight:600;border:1px dashed #f5cba7;border-radius:6px;">No promote opportunities in today\'s ECD cycle. Will retry tomorrow.</div>'
      : destinationBlocks
        + '<div style="margin-top:14px;font-size:12px;color:#666;line-height:1.5;">'
        + 'One featured destination per day with up to 3 hotels. Destinations rotate daily on a least-recently-used basis. '
        + 'Prices are per room per night, computed across all rooms \u00d7 nights in the requested booking window. '
        + 'Each card lists every room category where Eagle Crest beats the bedbank market.'
        + '</div>',
  ].join('');
  const promote = picked;

  return {
    subject: 'EQIS · Marketing — ' + promote.length + ' hotel' + (promote.length === 1 ? '' : 's') + ' to promote today',
    html: wrap({
      title: 'Hotels where Eagle Crest beats the market',
      preheader: promote.length + ' promotable hotel' + (promote.length === 1 ? '' : 's') + ' · ' + fmtINR(totalSavings) + ' total savings',
      bodyHtml: body,
      footerHtml: footer(input.runId),
    }),
    summaryLine: promote.length + ' promote · ' + fmtINR(totalSavings) + ' total savings',
    recordCount: promote.length,
  };
}

